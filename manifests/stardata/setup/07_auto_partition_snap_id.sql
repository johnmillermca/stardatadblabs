-- =============================================================================
-- 07_auto_partition_snap_id.sql
-- AUTO PARTITION setup — permanent defaults for StarData (Apache Doris)
--
-- What this does
-- ──────────────
-- 1. Sets max_auto_partition_num = 50000 (runtime config).
--    enable_auto_partition = true is already set permanently in fe.conf
--    via the stardata-fe-config ConfigMap — no ADMIN SET needed here.
--
-- 2. The Stardata FE patch (CreateTableInfo.java :: injectStardataFeatures)
--    automatically applies the following to every new OLAP table created in
--    any user database (excluding Doris system databases __internal_schema /
--    information_schema, and cache_system for regular tables — see below).
--
-- ─── Iceberg-type tables ─────────────────────────────────────────────────────
--
--   Triggered by:  PROPERTIES ("stardata.table_type" = "iceberg")
--
--   Injected automatically (skipped if the user already declared the column):
--     (a)  snap_id    BIGINT NOT NULL AUTO_INCREMENT(1)
--     (b)  created_at DATETIMEV2(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
--     (b)  updated_at DATETIMEV2(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
--                     [ON UPDATE CURRENT_TIMESTAMP]
--     (d)  AUTO PARTITION BY RANGE (date_trunc('day', created_at)) ()
--     (d)  DISTRIBUTED BY HASH(snap_id) BUCKETS AUTO
--     (c)  "storage_policy" = "sd_cold_1d"
--
--   The internal property "stardata.table_type" is stripped before Doris
--   analyzers run — it will not appear in SHOW CREATE TABLE.
--
--   cache_system is NOT excluded for iceberg-type tables — a table in
--   cache_system with stardata.table_type=iceberg receives full injection.
--
-- ─── Regular tables (no stardata.table_type property) ────────────────────────
--
--   Injected automatically:
--     (b)  created_at DATETIMEV2(0) NOT NULL DEFAULT CURRENT_TIMESTAMP
--          (skipped if the user already declared created_at)
--     (e)  AUTO PARTITION BY RANGE (date_trunc('day', created_at)) ()
--          DISTRIBUTED BY RANDOM BUCKETS AUTO    — when no UNIQUE KEY
--          (existing user distribution kept)      — when UNIQUE KEY declared
--     (c)  "storage_policy" = "sd_cold_1d"
--
--   cache_system is excluded for regular tables (Doris internal bookkeeping
--   tables must not receive auto-injected columns or policies).
--
-- ─── Opt-out of partition only ───────────────────────────────────────────────
--
--   Add  PROPERTIES ("stardata.disable_partition" = "true")  to suppress the
--   AUTO PARTITION injection.  created_at column and storage_policy are still
--   applied regardless of this flag.
--
-- ─── Example: iceberg-type table ─────────────────────────────────────────────
--
--   User writes:
--
--     CREATE TABLE analytics.events (
--         user_id  VARCHAR(64) NOT NULL,
--         payload  JSON
--     )
--     PROPERTIES ("stardata.table_type" = "iceberg");
--
--   FE produces the equivalent of:
--
--     CREATE TABLE analytics.events (
--         user_id    VARCHAR(64)  NOT NULL,
--         snap_id    BIGINT       NOT NULL AUTO_INCREMENT(1),
--         payload    JSON,
--         created_at DATETIMEV2   NOT NULL DEFAULT CURRENT_TIMESTAMP,
--         updated_at DATETIMEV2   NOT NULL DEFAULT CURRENT_TIMESTAMP
--     )
--     AUTO PARTITION BY RANGE (date_trunc('day', created_at)) ()
--     DISTRIBUTED BY HASH(snap_id) BUCKETS AUTO
--     PROPERTIES ("storage_policy" = "sd_cold_1d");
--
-- ─── Example: regular table (no unique key) ───────────────────────────────────
--
--   User writes:
--
--     CREATE TABLE analytics.logs (
--         level    TINYINT NOT NULL,
--         message  VARCHAR(1024)
--     );
--
--   FE produces the equivalent of:
--
--     CREATE TABLE analytics.logs (
--         level      TINYINT      NOT NULL,
--         message    VARCHAR(1024),
--         created_at DATETIMEV2   NOT NULL DEFAULT CURRENT_TIMESTAMP
--     )
--     AUTO PARTITION BY RANGE (date_trunc('day', created_at)) ()
--     DISTRIBUTED BY RANDOM BUCKETS AUTO
--     PROPERTIES ("storage_policy" = "sd_cold_1d");
--
-- ─── Example: regular table with unique key ───────────────────────────────────
--
--   User writes:
--
--     CREATE TABLE analytics.users (
--         user_id  VARCHAR(64) NOT NULL,
--         email    VARCHAR(256)
--     )
--     UNIQUE KEY (user_id)
--     DISTRIBUTED BY HASH(user_id) BUCKETS 10;
--
--   FE produces the equivalent of:
--
--     CREATE TABLE analytics.users (
--         user_id    VARCHAR(64)  NOT NULL,
--         email      VARCHAR(256),
--         created_at DATETIMEV2   NOT NULL DEFAULT CURRENT_TIMESTAMP
--     )
--     UNIQUE KEY (user_id)
--     AUTO PARTITION BY RANGE (date_trunc('day', created_at)) ()
--     DISTRIBUTED BY HASH(user_id) BUCKETS 10          -- user value kept
--     PROPERTIES ("storage_policy" = "sd_cold_1d");
--
-- ─── Example: opt-out of auto partition ──────────────────────────────────────
--
--   CREATE TABLE analytics.lookup (
--       code  VARCHAR(32) NOT NULL,
--       label VARCHAR(256)
--   )
--   PROPERTIES ("stardata.disable_partition" = "true");
--
--   FE produces:
--
--     CREATE TABLE analytics.lookup (
--         code       VARCHAR(32)  NOT NULL,
--         label      VARCHAR(256),
--         created_at DATETIMEV2   NOT NULL DEFAULT CURRENT_TIMESTAMP
--     )
--     DISTRIBUTED BY RANDOM BUCKETS AUTO
--     PROPERTIES ("storage_policy" = "sd_cold_1d");   -- hot→cold still active
--
-- Apply
-- ─────
--   export STARDATA_PASS="$(kubectl get secret stardata-credentials -n prod \
--       -o jsonpath='{.data.admin-password}' | base64 -d)"
--
--   mysql -h 192.168.1.50 -P 9030 -u root -p"${STARDATA_PASS}" \
--         < manifests/stardata/setup/07_auto_partition_snap_id.sql
--
-- Regression tests
-- ────────────────
--   See: manifests/stardata/setup/09_test_stardata_features.sql
-- =============================================================================

-- Raise the per-table auto-partition ceiling to 50 000 (default is 2 000).
-- Needed for tables with high created_at cardinality over long retention windows.
ADMIN SET FRONTEND CONFIG ("max_auto_partition_num" = "50000");
